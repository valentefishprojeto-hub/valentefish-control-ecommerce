import test from 'node:test';
import assert from 'node:assert/strict';
import {testDatabase} from './test-db.js';
import {createTools} from './tools.js';

test('tools consultam seed, preço atual, busca sem acento, frete e pedidos privados',async t=>{
  process.env.APP_URL='https://loja.test';
  const database=await testDatabase();t.after(()=>database.close());const {sql}=database;
  const [conversation]=await sql`insert into ig_conversations(igsid) values ('test') returning *`;
  const calls=[];
  const tools=createTools({sql,conversation,env:{MELHOR_ENVIO_TOKEN:'test',STORE_POSTAL_CODE:'21740000'},fetch:async(url,options)=>{
    calls.push(JSON.parse(options.body));return new Response(JSON.stringify([{id:1,name:'PAC',company:{name:'Correios'},price:'25.50',delivery_range:{min:3,max:6}}]));
  }});
  const found=await tools.buscar_produtos({termo:'yellow tang'});
  assert.equal(found[0].preco,'R$ 849,00');assert.equal(found[0].disponibilidade,'disponível');
  assert.ok(found[0].link.includes('utm_source=instagram'));assert.equal(found[0].stock_quantity,undefined);
  await sql`update products set stock_quantity=0,price_cents=85000 where slug='yellow-tang'`;
  const detail=await tools.detalhes_produto({slug:'yellow-tang'});
  assert.equal(detail.preco,'R$ 850,00');assert.equal(detail.disponibilidade,'não disponível no momento');assert.ok(detail.orcamento);
  assert.equal((await tools.buscar_produtos({termo:'carcaca'}))[0].nome,'Carcaça Slim para Filtro');
  assert.equal((await tools.listar_categorias()).length,5);
  await sql`update products set stock_quantity=2 where slug='yellow-tang'`;
  assert.equal((await tools.detalhes_produto({slug:'yellow-tang'})).disponibilidade,'últimas unidades');
  await sql`update products set active=false where slug='yellow-tang'`;
  assert.equal((await tools.buscar_produtos({termo:'yellow'})).length,0);
  assert.equal((await tools.detalhes_produto({slug:'yellow-tang'})).disponibilidade,'não disponível no momento');
  const quote=await tools.cotar_frete({cep:'20000-000',itens:[{slug:'coral-hammer-green',quantidade:2}]});
  assert.equal(quote.opcoes[0].preco,'R$ 25,50');assert.match(quote.aviso,/especialista/);
  assert.equal(calls[0].products[0].quantity,2);assert.equal(calls[0].products[0].weight,0.6);
  assert.equal((await sql`select * from shipping_quotes`).length,0);
  const unavailable=createTools({sql,conversation,env:{}});
  const fallback=await unavailable.cotar_frete({cep:'20000000',itens:[{slug:'coral-hammer-green',quantidade:1}]});
  assert.match(fallback.mensagem,/checkout/);assert.match(fallback.aviso,/especialista/);assert.match(fallback.link,/utm_source=instagram/);
  const failed=createTools({sql,conversation,env:{MELHOR_ENVIO_TOKEN:'test',STORE_POSTAL_CODE:'21740000'},fetch:async()=>new Response('{}',{status:500})});
  assert.match((await failed.cotar_frete({cep:'20000000',itens:[{slug:'coral-hammer-green',quantidade:1}]})).mensagem,/checkout/);
  assert.ok((await tools.cotar_frete({cep:'123',itens:[]})).erro);
  assert.equal(await tools.info_loja({topico:'parcelamento'}),null);
  assert.match(await tools.info_loja({topico:'contato_whatsapp'}),/utm_medium=dm/);
  const [order]=await sql`insert into orders(customer_email,customer_name,subtotal_cents,total_cents,shipping_address) values ('cliente@test.com','Privado',100,100,'{"street":"SEGREDO"}') returning number`;
  for(let i=0;i<5;i++) assert.deepEqual(await tools.consultar_pedido({numero:String(order.number),email:'errado@test.com'}),{encontrado:false});
  const limit=await tools.consultar_pedido({numero:String(order.number),email:'cliente@test.com'});
  assert.equal(limit.handoff,true);assert.equal((await sql`select * from ig_handoffs`).length,1);
  const [other]=await sql`insert into ig_conversations(igsid) values ('other') returning *`;
  const authorized=await createTools({sql,conversation:other}).consultar_pedido({numero:String(order.number),email:'CLIENTE@test.com'});
  assert.equal(authorized.status,'aguardando pagamento');assert.equal(JSON.stringify(authorized).includes('SEGREDO'),false);
  await tools.encaminhar_humano({motivo:'solicitação',resumo:'Cliente pede ajuda'});
  assert.equal((await sql`select * from ig_handoffs`).length,1);
  await sql`set role anon`;
  await assert.rejects(()=>sql`select * from ig_messages`,/permission denied/);
  await sql`reset role`;
});
